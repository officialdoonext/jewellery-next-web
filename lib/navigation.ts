export function findSubmenuItem(moduleSlug: string, subpageSlug: string) {
  const mod = NAVIGATION_MODULES.find((m) => m.slug === moduleSlug);
  if (!mod) return null;
  const item = mod.items.find((i) => i.slug === subpageSlug);
  return item ? { module: mod, item } : null;
}

